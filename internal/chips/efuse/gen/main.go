// Command gen writes tables.go of the efuse package: the eFuse fields of
// every chip from ESP-IDF's components/efuse/<chip>/esp_efuse_table*.csv
// and the key purposes from components/efuse/<chip>/include/
// esp_efuse_chip.h (ESP-IDF is Apache-2.0).
//
// It is run by `go generate` in internal/chips/efuse. By default it
// downloads the files of the pinned ESP-IDF commit from
// raw.githubusercontent.com; -src reads them from a local ESP-IDF
// checkout instead. To move to a newer ESP-IDF, change -commit (and
// -date) in the go:generate line of efuse.go, run `go generate`, and
// review the diff of tables.go.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// table is one field table: a chip, the revisions it is for, its CSVs
type table struct {
	key            string
	minRev, maxRev int // major*100+minor, inclusive
	csvs           []string
	varName        string
}

const anyRev = 9999

// The tables of ESP-IDF. The ESP32-P4 has a table for the revisions
// before v3.0 and one from v3.0 (components/efuse/esp32p4/sources.cmake,
// CONFIG_ESP32P4_SELECTS_REV_LESS_V3); the ESP32-H2 adds fields for
// v0.0 - v1.1 (esp_efuse_table_v0.0_v1.1.csv, "eFuses that only exist on
// ESP32-H2 v0.0 - v1.1").
var tables = []table{
	{key: "esp32", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32s2", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32s3", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32c2", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32c3", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32c5", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32c6", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32c61", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32h2", maxRev: 101, csvs: []string{"esp_efuse_table.csv", "esp_efuse_table_v0.0_v1.1.csv"}, varName: "tableESP32H2V0"},
	{key: "esp32h2", minRev: 102, maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32h21", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32h4", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
	{key: "esp32p4", maxRev: 299, csvs: []string{"esp_efuse_table.csv"}, varName: "tableESP32P4V0"},
	{key: "esp32p4", minRev: 300, maxRev: anyRev, csvs: []string{"esp_efuse_table_v3.0.csv"}, varName: "tableESP32P4V3"},
	{key: "esp32s31", maxRev: anyRev, csvs: []string{"esp_efuse_table.csv"}},
}

var (
	src    = flag.String("src", "", "a local ESP-IDF checkout; empty downloads -commit")
	commit = flag.String("commit", "", "the ESP-IDF commit")
	date   = flag.String("date", "", "the date of the commit, for the comment")
	out    = flag.String("out", "tables.go", "the file to write")
)

func main() {
	flag.Parse()
	if *src == "" && *commit == "" {
		fail(fmt.Errorf("-src or -commit is needed"))
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen/main.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// The eFuse fields of ESP-IDF (Apache-2.0) at commit %s (%s):\n", *commit, *date)
	fmt.Fprintf(&b, "// components/efuse/<chip>/esp_efuse_table*.csv and the key purposes of\n")
	fmt.Fprintf(&b, "// components/efuse/<chip>/include/esp_efuse_chip.h. Categories and the\n")
	fmt.Fprintf(&b, "// protection rules are derived by gen/main.go.\n\n")
	fmt.Fprintf(&b, "package efuse\n\n")

	var list []string
	purposes := map[string]bool{}
	for _, t := range tables {
		var rows []row
		for _, c := range t.csvs {
			data, err := fetch("components/efuse/" + t.key + "/" + c)
			if err != nil {
				fail(err)
			}
			r, err := parseCSV(data)
			if err != nil {
				fail(fmt.Errorf("%s/%s: %w", t.key, c, err))
			}
			rows = append(rows, r...)
		}
		fields := build(rows)
		wr, rd := rules(t.key, fields)
		name := t.varName
		if name == "" {
			name = "table" + goName(t.key)
		}
		writeTable(&b, name, t, fields, wr, rd)
		list = append(list, fmt.Sprintf("{key: %q, minRev: %d, maxRev: %d, fields: %s.fields, wr: %s.wr, rd: %s.rd},", t.key, t.minRev, t.maxRev, name, name, name))

		if !purposes[t.key] {
			purposes[t.key] = true
		}
	}
	fmt.Fprintf(&b, "var tableList = []*tableDef{\n")
	for _, l := range list {
		fmt.Fprintf(&b, "\t%s\n", l)
	}
	fmt.Fprintf(&b, "}\n\n")

	keys := make([]string, 0, len(purposes))
	for k := range purposes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(&b, "// keyPurposeNames are esp_efuse_purpose_t of each chip\n")
	fmt.Fprintf(&b, "var keyPurposeNames = map[string]map[uint64]string{\n")
	for _, k := range keys {
		data, err := fetch("components/efuse/" + k + "/include/esp_efuse_chip.h")
		if err != nil {
			fail(err)
		}
		p := parsePurposes(data)
		if len(p) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {", k)
		vs := make([]int, 0, len(p))
		for v := range p {
			vs = append(vs, v)
		}
		sort.Ints(vs)
		for _, v := range vs {
			fmt.Fprintf(&b, "%d: %q, ", v, p[v])
		}
		fmt.Fprintf(&b, "},\n")
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile(*out+".broken", b.Bytes(), 0o644)
		fail(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

func goName(key string) string {
	return "ESP32" + strings.ToUpper(strings.TrimPrefix(key, "esp32"))
}

func fetch(path string) ([]byte, error) {
	if *src != "" {
		return os.ReadFile(filepath.Join(*src, filepath.FromSlash(path)))
	}
	url := "https://raw.githubusercontent.com/espressif/esp-idf/" + *commit + "/" + path
	c := &http.Client{Timeout: 60 * time.Second}
	resp, err := c.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// row is a line of esp_efuse_table.csv
type row struct {
	name          string // empty: another part of the field above
	blk, bit, n   int
	aliases       []string
	desc          string
	enum          map[int]string
	enumKeysOrder []int
}

var (
	reAliases = regexp.MustCompile(`^\[([^\]]*)\]\s*`)
	reEnum    = regexp.MustCompile(`\{([^{}]*)\}\s*$`)
	reEnumVal = regexp.MustCompile(`^\s*(-?\d+)\s*:\s*"([^"]*)"\s*$`)
)

func parseCSV(data []byte) ([]row, error) {
	var rows []row
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		cols := strings.SplitN(line, ",", 5)
		if len(cols) < 4 {
			return nil, fmt.Errorf("bad line %q", line)
		}
		var r row
		r.name = strings.TrimSpace(cols[0])
		blk := strings.TrimSpace(cols[1])
		if !strings.HasPrefix(blk, "EFUSE_BLK") {
			return nil, fmt.Errorf("bad block in %q", line)
		}
		var err error
		if r.blk, err = strconv.Atoi(strings.TrimPrefix(blk, "EFUSE_BLK")); err != nil {
			return nil, fmt.Errorf("bad block in %q", line)
		}
		if r.bit, err = strconv.Atoi(strings.TrimSpace(cols[2])); err != nil {
			return nil, fmt.Errorf("bad bit in %q", line)
		}
		n := strings.TrimSpace(cols[3])
		if n == "MAX_BLK_LEN" {
			// esp_efuse_table.c of the ESP32: 256 bits, 192 with the 3/4
			// coding scheme (handled when reading)
			r.n = 256
		} else if r.n, err = strconv.Atoi(n); err != nil {
			return nil, fmt.Errorf("bad length in %q", line)
		}
		if len(cols) == 5 {
			c := strings.TrimSpace(cols[4])
			if m := reAliases.FindStringSubmatch(c); m != nil {
				r.aliases = strings.Fields(m[1])
				c = c[len(m[0]):]
			}
			if m := reEnum.FindStringSubmatchIndex(c); m != nil {
				body := c[m[2]:m[3]]
				enum := map[int]string{}
				ok := true
				for _, part := range strings.Split(body, ";") {
					vm := reEnumVal.FindStringSubmatch(part)
					if vm == nil {
						ok = false
						break
					}
					v, _ := strconv.Atoi(vm[1])
					enum[v] = vm[2]
					r.enumKeysOrder = append(r.enumKeysOrder, v)
				}
				if ok {
					r.enum = enum
					c = strings.TrimSpace(c[:m[0]])
				} else {
					r.enumKeysOrder = nil
				}
			}
			r.desc = c
		}
		rows = append(rows, r)
	}
	return rows, sc.Err()
}

type part struct{ blk, bit, n int }

type field struct {
	name, desc, cat string
	aliases         []string
	parts           []part
	enum            map[int]string
}

// build joins the parts of the fields: a row without a name continues the
// field above it. A field of a later CSV (the v0.0_v1.1 additions) with
// the name of an earlier one replaces it.
func build(rows []row) []*field {
	var fields []*field
	byName := map[string]int{}
	for _, r := range rows {
		if r.name == "" {
			if len(fields) == 0 {
				continue
			}
			f := fields[len(fields)-1]
			f.parts = append(f.parts, part{r.blk, r.bit, r.n})
			continue
		}
		f := &field{name: r.name, desc: r.desc, aliases: r.aliases, enum: r.enum,
			parts: []part{{r.blk, r.bit, r.n}}}
		f.cat = category(f.name)
		if i, ok := byName[r.name]; ok {
			fields[i] = f
			continue
		}
		byName[r.name] = len(fields)
		fields = append(fields, f)
	}
	return fields
}

// rule is a bit of WR_DIS or RD_DIS and the bits it protects
type rule struct {
	bit, blk, lo, hi int
	target           string
}

var reBlockComment = regexp.MustCompile(`(?i)(?:wr|rd)_dis of BLOCK(\d+)$`)

// rules derives the protection from the WR_DIS.X and RD_DIS.X fields: the
// bit of X in WR_DIS (RD_DIS) protects the bits of field X. In BLOCK1 and
// up a bit protects the whole block (the TRMs: write protection of
// BLOCK1..n is per block; read protection exists for whole blocks only),
// except the halves of the ESP32-C2's key block (RD_DIS.KEY0.LOW / .HI).
func rules(key string, fields []*field) (wr, rd []rule) {
	byName := map[string]*field{}
	for _, f := range fields {
		if strings.HasPrefix(f.name, "WR_DIS.") || strings.HasPrefix(f.name, "RD_DIS.") {
			continue
		}
		byName[f.name] = f
		for _, a := range f.aliases {
			if _, ok := byName[a]; !ok {
				byName[a] = f
			}
		}
	}
	for _, f := range fields {
		var kind, target string
		switch {
		case strings.HasPrefix(f.name, "WR_DIS."):
			kind, target = "wr", strings.TrimPrefix(f.name, "WR_DIS.")
		case strings.HasPrefix(f.name, "RD_DIS."):
			kind, target = "rd", strings.TrimPrefix(f.name, "RD_DIS.")
		case strings.HasPrefix(f.name, "WR_DIS_"):
			// ESP32-H2 v0.0 - v1.1: "WR_DIS_ECDSA_FORCE_USE_HARDWARE_K"
			kind, target = "wr", strings.TrimPrefix(f.name, "WR_DIS_")
		default:
			continue
		}
		if len(f.parts) != 1 || f.parts[0].blk != 0 {
			fmt.Fprintf(os.Stderr, "gen: %s: %s is not in BLOCK0, skipped\n", key, f.name)
			continue
		}
		// a protection field of several bits (the C2's RD_DIS.KEY0) is
		// made of the single-bit ones that follow it
		if f.parts[0].n != 1 {
			continue
		}
		bit := f.parts[0].bit
		var add []rule
		half := ""
		t, ok := byName[target]
		if !ok {
			if i := strings.LastIndex(target, "."); i > 0 {
				half = target[i+1:]
				t, ok = byName[target[:i]]
			}
		}
		if !ok {
			// names the tables use for a field without that alias:
			// BLOCK_SYS_DATA2 is SYS_DATA_PART2 (BLOCK10), CUSTOM_MAC is
			// the ESP32's MAC_CUSTOM; KEY_PURPOSE_0_H is the high part of
			// the ESP32-P4 v3.0's KEY_PURPOSE_0 (one field of two parts)
			for _, alt := range []string{knownNames[target], strings.TrimSuffix(target, "_H"),
				strings.TrimSuffix(strings.TrimSuffix(target, "_LO"), "_HI")} {
				if t, ok = byName[alt]; ok && alt != "" {
					break
				}
			}
		}
		switch {
		case ok:
			for _, p := range t.parts {
				lo, hi := p.bit, p.bit+p.n
				if p.blk != 0 {
					lo, hi = 0, 256
					switch half {
					case "LOW":
						hi = 128
					case "HI":
						lo = 128
					}
				}
				add = append(add, rule{bit, p.blk, lo, hi, target})
			}
		default:
			m := reBlockComment.FindStringSubmatch(f.desc)
			if m == nil {
				if strings.HasPrefix(target, "BLOCK") || strings.HasPrefix(target, "BLK") {
					s := strings.TrimLeft(target, "BLOCK")
					if n, err := strconv.Atoi(s); err == nil {
						m = []string{"", strconv.Itoa(n)}
					}
				}
			}
			if m == nil && target == "BLOCK_SYS_DATA2" {
				// SYS_DATA_PART2 is the last block (efuse_chip.h:
				// EFUSE_BLK_SYS_DATA_PART2); without its own field it is
				// the last block that has fields
				last := 0
				for _, g := range fields {
					for _, p := range g.parts {
						last = max(last, p.blk)
					}
				}
				m = []string{"", strconv.Itoa(last)}
			}
			if m == nil {
				fmt.Fprintf(os.Stderr, "gen: %s: %s protects nothing known, skipped\n", key, f.name)
				continue
			}
			n, _ := strconv.Atoi(m[1])
			add = append(add, rule{bit, n, 0, 256, target})
		}
		if kind == "wr" {
			wr = append(wr, add...)
		} else {
			rd = append(rd, add...)
		}
	}
	return dedup(wr), dedup(rd)
}

var knownNames = map[string]string{
	"BLOCK_SYS_DATA2": "SYS_DATA_PART2",
	"CUSTOM_MAC":      "MAC_CUSTOM",
}

func dedup(rs []rule) []rule {
	seen := map[[4]int]bool{}
	var out []rule
	for _, r := range rs {
		k := [4]int{r.bit, r.blk, r.lo, r.hi}
		if seen[k] {
			continue
		}
		seen[k] = true
		out = append(out, r)
	}
	return out
}

func writeTable(b *bytes.Buffer, name string, t table, fields []*field, wr, rd []rule) {
	fmt.Fprintf(b, "// %s: components/efuse/%s/%s\n", name, t.key, strings.Join(t.csvs, ", "))
	fmt.Fprintf(b, "var %s = tableDef{\n", name)
	fmt.Fprintf(b, "\tfields: []fieldDef{\n")
	for _, f := range fields {
		fmt.Fprintf(b, "\t\t{name: %q, cat: %q, desc: %q", f.name, f.cat, f.desc)
		if len(f.aliases) > 0 {
			fmt.Fprintf(b, ", aliases: %#v", f.aliases)
		}
		fmt.Fprintf(b, ", parts: []part{")
		for _, p := range f.parts {
			fmt.Fprintf(b, "{%d, %d, %d},", p.blk, p.bit, p.n)
		}
		fmt.Fprintf(b, "}")
		if len(f.enum) > 0 {
			vs := make([]int, 0, len(f.enum))
			for v := range f.enum {
				vs = append(vs, v)
			}
			sort.Ints(vs)
			fmt.Fprintf(b, ", enum: map[uint64]string{")
			for _, v := range vs {
				fmt.Fprintf(b, "%d: %q,", v, f.enum[v])
			}
			fmt.Fprintf(b, "}")
		}
		fmt.Fprintf(b, "},\n")
	}
	fmt.Fprintf(b, "\t},\n")
	for _, k := range []struct {
		n  string
		rs []rule
	}{{"wr", wr}, {"rd", rd}} {
		fmt.Fprintf(b, "\t%s: []protRule{\n", k.n)
		for _, r := range k.rs {
			fmt.Fprintf(b, "\t\t{bit: %d, blk: %d, lo: %d, hi: %d, target: %q},\n", r.bit, r.blk, r.lo, r.hi, r.target)
		}
		fmt.Fprintf(b, "\t},\n")
	}
	fmt.Fprintf(b, "}\n\n")
}

var rePurpose = regexp.MustCompile(`^\s*ESP_EFUSE_KEY_PURPOSE_([A-Z0-9_]+)\s*=\s*(\d+)\s*,`)

// parsePurposes reads esp_efuse_purpose_t; aliases (a name for a value) and
// MAX are left out. Both sides of an #if are taken: their values don't
// collide (the ESP32-P4 v3.0 only adds values).
func parsePurposes(data []byte) map[int]string {
	p := map[int]string{}
	in := false
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		l := sc.Text()
		if strings.Contains(l, "typedef enum") {
			in = true
			continue
		}
		if strings.Contains(l, "} esp_efuse_purpose_t") {
			break
		}
		if !in {
			continue
		}
		m := rePurpose.FindStringSubmatch(l)
		if m == nil || m[1] == "MAX" {
			continue
		}
		v, _ := strconv.Atoi(m[2])
		if _, ok := p[v]; !ok {
			p[v] = m[1]
		}
	}
	return p
}

// category groups the fields for the UI
func category(name string) string {
	has := func(s ...string) bool {
		for _, x := range s {
			if strings.Contains(name, x) {
				return true
			}
		}
		return false
	}
	pre := func(s ...string) bool {
		for _, x := range s {
			if strings.HasPrefix(name, x) {
				return true
			}
		}
		return false
	}
	switch {
	case pre("WR_DIS", "RD_DIS"):
		return CatProtection
	case pre("MAC") || has("CUSTOM_MAC", "MAC_CUSTOM"):
		return CatMAC
	case pre("KEY", "BLOCK1", "BLOCK2", "KM_", "LOCK_KM", "HUK") || has("KEY_MANAGER", "XTS_KEY_LENGTH"):
		return CatKeys
	case pre("FLASH_CRYPT", "SPI_BOOT_CRYPT", "SECURE_", "ABS_DONE", "ECDSA", "ECC_", "CRYPT_DPA",
		"SEC_DPA", "XTS_DPA", "DIS_SM_CRYPT", "ENA_XTS", "ENA_SPI_BOOT_CRYPT", "BOOTLOADER_ANTI_ROLLBACK",
		"DISABLE_DL_", "DIS_SWD", "SDC_", "FORCE_DISABLE_SW_INIT_KEY", "CONSOLE_DEBUG", "DIS_DIRECT_BOOT",
		"DIS_LEGACY_SPI_BOOT", "ENABLE_SECURITY_DOWNLOAD", "STRAP_JTAG", "RE_ENABLE_JTAG") ||
		has("JTAG", "DOWNLOAD", "GLITCH"):
		return CatSecurity
	case pre("WAFER_VERSION", "BLK_VERSION", "PKG_VERSION", "CHIP_", "DISABLE_WAFER", "DISABLE_BLK",
		"BLOCK0_VERSION", "OPTIONAL_UNIQUE_ID"):
		return CatVersion
	case pre("FLASH_", "PSRAM_", "SPI_PAD", "VDD_SPI", "XPD_SDIO", "SPI_LDO", "PMU_FLASH", "PIN_POWER"):
		return CatFlash
	case pre("ADC", "TEMP", "OCODE", "K_RTC", "K_DIG", "V_RTC", "V_DIG", "THRES", "RTCCALIB", "RXIQ",
		"PA_TRIM", "DCDC", "LDO_", "TRIM_", "REF_CURR", "RES_TUNE", "PVT_", "CLK8M", "VOL_LEVEL",
		"ADJUST_", "IO_LDO", "ACTIVE_", "DSLP", "LSLP", "SLP_", "HI_DOUT", "INITCODE", "VDD_3V4",
		"LP_", "BLK3_PART", "DIG_", "RTC_", "DBIAS", "PUMP_", "HP_PWR", "ADC_") || has("DBIAS", "_LDO"):
		return CatCalibration
	case pre("USER_DATA", "SYS_DATA", "BLOCK_USR"):
		return CatUser
	}
	return CatConfig
}

// The categories; the same constants are in efuse.go
const (
	CatProtection  = "protection"
	CatMAC         = "MAC"
	CatKeys        = "keys"
	CatSecurity    = "security"
	CatVersion     = "version"
	CatFlash       = "flash/PSRAM"
	CatCalibration = "calibration"
	CatUser        = "user data"
	CatConfig      = "config"
)
